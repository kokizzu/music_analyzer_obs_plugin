#!/usr/bin/env python3
"""Freeze and export the second-stage native Voice proposal verifier."""
import argparse
import hashlib
import json
import math
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--freeze', action='store_true')
    parser.add_argument('--goldens', action='store_true')
    args = parser.parse_args()
    canonical = ROOT / 'models/native_mfcc_voice.json'
    source = ROOT / 'build/next_detection/native_mfcc_voice.json' if args.freeze else canonical
    state = json.loads(source.read_text())
    assert state['decision'] == 'candidate'
    assert all(not row['correct_losses'] and not row['unscored_removals'] for row in state['metrics'].values())
    assert len(state['features']) == 38 and len(state['model']['trees']) == 24
    assert state['parent_model_sha256'] == digest(ROOT / 'models/keyboard_voice_classifier.json')
    if args.goldens:
        from evaluate_native_mfcc_voice import transformed, lower_probability, BASE_FEATURES
        parent = json.loads((ROOT / 'models/keyboard_voice_classifier.json').read_text())
        capture = next(ROOT / p for p in state['inputs'] if p.endswith('candidates.tsv'))
        selected = {True: [], False: []}
        protected = {'vocal_acoustic_000-065-100': {8800},
                     'vocal_acoustic_000-070-075': {6400, 13600, 15200, 23200, 32800},
                     'vocal_acoustic_000-069-050': {47200, 49600}}
        regressions = []
        with capture.open() as stream:
            for row in csv.DictReader(stream, delimiter='\t'):
                if row['mfcc_valid'] != '1':
                    continue
                if lower_probability(parent['model'], transformed(row, BASE_FEATURES)) < parent['threshold']:
                    continue
                score = lower_probability(state['model'], transformed(row, state['features']))
                flag = score >= state['threshold']
                if (int(row['end_sample']) in protected.get(row['sample_id'], set()) and
                        int(row['midi']) == int(row['sample_id'].rsplit('-', 2)[1])):
                    assert not flag, 'Known correct Voice regression must be vetoed'
                    regressions.append(dict(raw=[float(row[key]) for key in state['features']], score=score,
                                            sample_id=row['sample_id'], end_sample=row['end_sample'], protected=True))
                if len(selected[flag]) < 16:
                    selected[flag].append(dict(raw=[float(row[key]) for key in state['features']], score=score,
                                               sample_id=row['sample_id'], end_sample=row['end_sample']))
        assert all(selected.values())
        assert len(regressions) == 8
        destination = ROOT / 'tests/native_mfcc_voice_vectors.json'
        destination.write_text(json.dumps(dict(model_sha256=digest(canonical), vectors=selected[True] + selected[False] + regressions), indent=2) + '\n')
        print('Exported 32 parity vectors and eight protected Voice regressions')
        return
    if args.freeze:
        assert all(digest(ROOT / p) == expected for p, expected in state['inputs'].items())
        temporary = canonical.with_suffix('.tmp')
        temporary.write_bytes(source.read_bytes())
        temporary.replace(canonical)
        print('Frozen verifier', digest(canonical))
        return
    nodes = []
    def flatten(tree, depth=0):
        assert depth <= 8
        index = len(nodes)
        nodes.append(None)
        if isinstance(tree, list):
            assert len(tree) == 2 and all(math.isfinite(v) and 0 <= v <= 1 for v in tree)
            nodes[index] = (-1, 0, 0, 0., tree[0])
        else:
            assert 0 <= tree['feature'] < 38 and math.isfinite(tree['threshold'])
            left, right = flatten(tree['left'], depth + 1), flatten(tree['right'], depth + 1)
            nodes[index] = (tree['feature'], left, right, tree['threshold'], 0.)
        return index
    roots = [flatten(tree) for tree in state['model']['trees']]
    assert len(nodes) <= 4096
    text = '// Generated by make generate-native-mfcc-voice; do not edit.\n#pragma once\n#include <array>\nnamespace mao { namespace native_mfcc_voice {\n'
    text += 'inline constexpr const char *model_sha256 = "' + digest(source) + '";\n'
    text += 'inline constexpr const char *parent_sha256 = "' + state['parent_model_sha256'] + '";\n'
    text += 'struct Node { int feature, left, right; double threshold, probability; };\n'
    text += 'inline constexpr double threshold = ' + repr(state['threshold']) + ';\n'
    text += 'inline constexpr std::array<int, 24> roots = {{' + ','.join(map(str, roots)) + '}};\n'
    text += 'inline constexpr std::array<Node, ' + str(len(nodes)) + '> nodes = {{\n'
    text += ''.join('{' + ','.join(map(repr, node)) + '},\n' for node in nodes)
    text += '}};\n}} // namespace mao::native_mfcc_voice\n'
    destination = ROOT / 'src/native_mfcc_voice_model_data.hpp'
    temporary = destination.with_suffix('.tmp')
    temporary.write_text(text)
    temporary.replace(destination)
    print('Exported', len(nodes), 'nodes; verifier', digest(source))


if __name__ == '__main__':
    main()
