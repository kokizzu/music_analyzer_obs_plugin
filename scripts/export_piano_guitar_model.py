#!/usr/bin/env python3
"""Freeze the measured duplicate verifier and generate bounded native data."""
import argparse
import csv
import hashlib
import json
import math
from itertools import groupby

from evaluate_guitar_duplicate_model import FEATURES as BASE_FEATURES, eligible, features, lower_probability
from evaluate_guitar_music_model import frame_context
from routing_duration_baseline import ROOT, atomic_json, digest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--freeze', action='store_true')
    args = parser.parse_args()
    canonical = ROOT / 'models/piano_guitar_verifier.json'
    source = ROOT / 'build/routing_guitar_music_model.json' if args.freeze else canonical
    state = json.loads(source.read_text())
    assert state['decision'] == 'candidate_for_native_replay'
    assert len(state['features']) == 62 and len(state['model']['trees']) == 24
    assert all(not metric['correct_guitar_losses'] and not metric['protected_guitar_row_changes'] for metric in state['metrics'].values())
    if args.freeze:
        assert all(digest(ROOT / p) == checksum for p, checksum in state['inputs'].items())
        canonical.parent.mkdir(exist_ok=True)
        temporary = canonical.with_suffix('.tmp')
        temporary.write_bytes(source.read_bytes())
        temporary.replace(canonical)
        # Audio-independent parity fixtures contain actual fitting/cutoff rows,
        # with protected and positive decisions; they do not retrain the forest.
        cases = {True: [], False: []}
        for name in state['inputs']:
            if not name.endswith('.tsv'):
                continue
            with (ROOT / name).open() as stream:
                for _, frame in groupby(csv.DictReader(stream, delimiter='\t'), key=lambda row: row['end_sample']):
                    candidates = list(frame)
                    context = frame_context(candidates)
                    for row in candidates:
                        if not eligible(row):
                            continue
                        raw = [float(row[key]) for key in BASE_FEATURES] + context
                        probability = lower_probability(state['model'], features(row) + context)
                        decision = probability >= state['threshold']
                        if len(cases[decision]) < 16:
                            cases[decision].append(dict(raw=raw, probability=probability))
            if all(len(rows) == 16 for rows in cases.values()):
                break
        assert all(len(rows) == 16 for rows in cases.values())
        atomic_json(ROOT / 'tests/piano_guitar_vectors.json', dict(model_sha256=digest(canonical), cases=cases[True] + cases[False]))
        print('Frozen native-replay candidate', digest(canonical))
        return
    nodes = []
    def flatten(tree, depth=0):
        assert depth <= 8
        index = len(nodes)
        nodes.append(None)
        if isinstance(tree, list):
            assert len(tree) == 2 and all(math.isfinite(v) and 0 <= v <= 1 for v in tree)
            nodes[index] = (-1, 0, 0, 0., tree[0])
        else:
            assert 0 <= tree['feature'] < 62 and math.isfinite(tree['threshold'])
            left, right = flatten(tree['left'], depth + 1), flatten(tree['right'], depth + 1)
            nodes[index] = (tree['feature'], left, right, tree['threshold'], 0.)
        return index
    roots = [flatten(tree) for tree in state['model']['trees']]
    assert len(nodes) <= 4096
    text = '// Generated by make generate-piano-guitar-model; do not edit.\n#pragma once\n#include <array>\nnamespace mao { namespace piano_guitar_model {\n'
    text += 'inline constexpr const char *model_sha256 = "' + digest(source) + '";\n'
    text += 'inline constexpr double threshold = ' + repr(state['threshold']) + ';\n'
    text += 'inline constexpr double uncertainty = ' + repr(state['boundary_uncertainty']) + ';\n'
    text += 'struct Node { int feature, left, right; double threshold, probability; };\n'
    text += 'inline constexpr std::array<int, 24> roots = {{' + ','.join(map(str, roots)) + '}};\n'
    text += 'inline constexpr std::array<Node, ' + str(len(nodes)) + '> nodes = {{\n'
    text += ''.join('{' + ','.join(map(repr, node)) + '},\n' for node in nodes)
    text += '}};\n}} // namespace mao::piano_guitar_model\n'
    destination = ROOT / 'src/piano_guitar_model_data.hpp'
    temporary = destination.with_suffix('.tmp')
    temporary.write_text(text)
    temporary.replace(destination)
    print('Generated', len(nodes), 'nodes; model', digest(source))


if __name__ == '__main__':
    main()
