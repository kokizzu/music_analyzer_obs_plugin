#!/usr/bin/env python3
"""Export the measured frozen forest as bounded, allocation-free C++ data."""
import hashlib
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--freeze", action="store_true")
    args = parser.parse_args()
    canonical = ROOT / "models/keyboard_voice_classifier.json"
    source = ROOT / "build/next_detection/keyboard_voice_classifier.json" if args.freeze else canonical
    state = json.loads(source.read_text())
    assert state["decision"] == "candidate"
    assert all(not row["correct_losses"] for row in state["metrics"].values())
    assert len(state["features"]) == 14 and len(state["model"]["trees"]) == 24
    if args.freeze:
        assert all(hashlib.sha256((ROOT / p).read_bytes()).hexdigest() == expected for p, expected in state["inputs"].items())
        canonical.parent.mkdir(parents=True, exist_ok=True)
        temporary = canonical.with_suffix(".tmp")
        temporary.write_bytes(source.read_bytes())
        temporary.replace(canonical)
        print("Frozen model", hashlib.sha256(canonical.read_bytes()).hexdigest())
        return
    nodes = []
    def flatten(tree, depth=0):
        assert depth <= 8
        index = len(nodes)
        nodes.append(None)
        if isinstance(tree, list):
            assert len(tree) == 2 and all(math.isfinite(v) and 0 <= v <= 1 for v in tree)
            nodes[index] = (-1, 0, 0, 0., tree[0])
        else:
            assert 0 <= tree["feature"] < 14 and math.isfinite(tree["threshold"])
            left, right = flatten(tree["left"], depth + 1), flatten(tree["right"], depth + 1)
            nodes[index] = (tree["feature"], left, right, tree["threshold"], 0.)
        return index
    roots = [flatten(tree) for tree in state["model"]["trees"]]
    assert len(nodes) <= 4096
    text = "// Generated by make generate-keyboard-voice-model; do not edit.\n#pragma once\n#include <array>\nnamespace mao { namespace keyboard_voice_model {\n"
    text += 'inline constexpr const char *model_sha256 = "' + hashlib.sha256(source.read_bytes()).hexdigest() + '";\n'
    text += "struct Node { int feature, left, right; double threshold, probability; };\n"
    text += "inline constexpr double threshold = " + repr(state["threshold"]) + ";\n"
    text += "inline constexpr std::array<int, 24> roots = {{" + ",".join(map(str, roots)) + "}};\n"
    text += "inline constexpr std::array<Node, " + str(len(nodes)) + "> nodes = {{\n"
    text += "".join("{" + ",".join(map(repr, node)) + "},\n" for node in nodes)
    text += "}};\n}} // namespace mao::keyboard_voice_model\n"
    destination = ROOT / "src/keyboard_voice_model_data.hpp"
    temporary = destination.with_suffix(".tmp")
    temporary.write_text(text)
    temporary.replace(destination)
    print("Exported", len(nodes), "nodes; model", hashlib.sha256(source.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
